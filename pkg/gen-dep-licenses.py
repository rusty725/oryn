#!/usr/bin/env python3
"""Write LICENSES-dependencies.txt: the license notices of every Rust crate
compiled into the oryn binary, as their licenses require for binary
packages (.deb, .rpm, pacman). Run from the repository root after changing
dependencies:  python3 pkg/gen-dep-licenses.py
"""
import hashlib, json, os, re, subprocess, sys

TARGET = sys.argv[1] if len(sys.argv) > 1 else "x86_64-unknown-linux-gnu"

tree = subprocess.run(
    ["cargo", "tree", "-e", "normal", "--target", TARGET, "--prefix", "none", "--format", "{p}"],
    check=True, capture_output=True, text=True).stdout
wanted = set()
for line in tree.splitlines():
    m = re.match(r"(\S+) v(\S+)", line)
    if m and m.group(1) != "oryn":
        wanted.add((m.group(1), m.group(2)))

meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"],
                                 check=True, capture_output=True, text=True).stdout)
texts = {}   # hash -> (text, [crates])
missing = []
rows = []
for p in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
    if (p["name"], p["version"]) not in wanted:
        continue
    lic = p.get("license") or "(see license file)"
    rows.append(f'{p["name"]} {p["version"]}: {lic}')
    d = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(d)
                   if re.match(r"(?i)^(licen[cs]e|copying|notice|unlicense)", f) and os.path.isfile(os.path.join(d, f)))
    if not files:
        missing.append(f'{p["name"]} {p["version"]} ({lic})')
    for f in files:
        t = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
        h = hashlib.sha256(t.encode()).hexdigest()
        texts.setdefault(h, (t, []))[1].append(f'{p["name"]} {p["version"]} ({f})')

out = ["Licenses of the Rust crates compiled into oryn",
       "=" * 47, "",
       "Oryn itself is MIT licensed (see LICENSE); code adapted from LACT and",
       "nvidia-gpu-sensors is credited in THIRD_PARTY_NOTICES.md. The prebuilt",
       "oryn binary also contains the crates below. Each is used under the",
       "license shown (for \"A OR B\", either one); their license texts follow.",
       "Generated by pkg/gen-dep-licenses.py.", "", "Crates", "------"]
out += rows
if missing:
    out += ["", "No license file shipped (license as declared above):"] + missing
for t, crates in texts.values():
    out += ["", "", "-" * 78, "Used by: " + ", ".join(crates), "-" * 78, "", t]
open("LICENSES-dependencies.txt", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"{len(rows)} crates, {len(texts)} distinct license texts, {len(missing)} without a file")
